#!/usr/bin/env python3
"""Compile the port's runtime pieces that stand in for PS2 functions into build/port/obj/port__*.o,
so port/tools/resolve.py maps their PS2 addresses like any decompiled function:
  port/runtime/kernel.c, ps2_libc.c        (the EE kernel, the hand-written library routines)
  build/port/gen/kcalls.c                  (generated: one function per kernel-call stub of
                                            config/asm_functions.txt, calling ps2_syscall(N, ...))
build/port/asm_funcs.json (address, syscall number, name of every asm function) is written in WSL:
  see port/README.md.

    python port/tools/build_runtime.py
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MINGW = os.environ.get("MINGW32", r"C:\msys64\mingw32\bin")
os.environ["PATH"] = MINGW + os.pathsep + os.environ["PATH"]
OUT = os.path.join(ROOT, "build", "port")
GEN = os.path.join(OUT, "gen")
OBJ = os.path.join(OUT, "obj")


def main():
    os.makedirs(GEN, exist_ok=True)
    funcs = json.load(open(os.path.join(OUT, "asm_funcs.json")))
    with open(os.path.join(GEN, "kcalls.c"), "w", newline="\n") as f:
        f.write("/* generated by port/tools/build_runtime.py: the EE kernel-call stubs */\n"
                "extern int ps2_syscall(int n, int a0, int a1, int a2, int a3);\n")
        n = 0
        for fn in funcs:
            if fn["syscall"] is None:
                continue
            f.write(f"int func_{fn['addr'].upper()}(int a0, int a1, int a2, int a3) "
                    f"{{ return ps2_syscall({fn['syscall']}, a0, a1, a2, a3); }}\n")
            n += 1
    print(f"{n} kernel-call stubs -> build/port/gen/kcalls.c")
    for src, name in [(os.path.join(ROOT, "port", "runtime", "kernel.c"), "port__kernel.o"),
                      (os.path.join(ROOT, "port", "runtime", "ps2_libc.c"), "port__ps2_libc.o"),
                      (os.path.join(GEN, "kcalls.c"), "port__kcalls.o")]:
        r = subprocess.run([os.path.join(MINGW, "gcc.exe"), "-m32", "-c", "-O0", "-g", "-fno-omit-frame-pointer", "-w", "-fno-builtin", src,
                            "-o", os.path.join(OBJ, name)], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"{src}:\n{r.stderr}")
    print("runtime objects -> build/port/obj/port__*.o")


if __name__ == "__main__":
    main()
